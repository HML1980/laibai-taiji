def get_hexagram_context(hexagram_num, category=None, yao=None):
    """
    根據卦號、問題類型、動爻獲取相關解讀資料
    
    Args:
        hexagram_num: 卦號 (1-64)
        category: 問題類型 ('career'/'love'/'wealth'/'health'/'general')
        yao: 動爻 (如 '初九', '六二' 等)
    
    Returns:
        相關的解讀文本
    """
    if hexagram_num not in ZHOUYI_DATA:
        return ''
    
    h = ZHOUYI_DATA[hexagram_num]
    context = []
    
    # 卦的哲學含義
    if h['philosophy']:
        context.append(f"【卦義】{h['philosophy'][:300]}")
    
    # 根據問題類型選擇相關解讀
    if category in ['career', 'work', '事業']:
        if h['career']:
            context.append(f"【事業】{h['career']}")
        if h['business']:
            context.append(f"【經商】{h['business']}")
    elif category in ['love', 'relationship', '感情', '婚姻']:
        if h['love']:
            context.append(f"【婚戀】{h['love']}")
    elif category in ['wealth', 'money', '財運', '投資']:
        if h['business']:
            context.append(f"【財運】{h['business']}")
    elif category in ['decision', 'choice', '決策', '抉擇']:
        if h['decision']:
            context.append(f"【決策】{h['decision']}")
    else:
        # 一般問題，給出綜合建議
        if h['decision']:
            context.append(f"【建議】{h['decision'][:200]}")
    
    # 動爻解讀
    if yao and yao in h['yaos']:
        yao_phil = h['yaos'][yao].get('philosophy', '')
        if yao_phil:
            context.append(f"【動爻 {yao}】{yao_phil[:300]}")
    
    return '\n'.join(context)
